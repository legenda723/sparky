export interface PhraseContext {
  today: string
  /** Первый день с уроком; нет — уроков ещё не было. */
  firstDay?: string
  /** Стрик сейчас (с учётом пропусков). */
  streak: number
  /** «Знаю слов». */
  words: number
  /** Дней с уроками. */
  activeDays: number
}

export interface Phrase {
  group: string
  text: string
}

/** Группы по вехам, которые уже пройдены (самая высокая в каждом ряду), и свежие — пройденные ровно сегодня. */
export function phraseGroups(c: PhraseContext): { all: string[]; fresh: string[] } {
  if (!c.firstDay) return { all: ['zero'], fresh: [] }
  const passed = Math.max(0, daysBetween(c.firstDay, c.today))
  const all: string[] = []
  const fresh: string[] = []
  const time = passed === 0 ? 0 : [...TIME_MILESTONES].reverse().find((m) => passed >= m)
  if (time !== undefined) {
    all.push(`t${time}`)
    if (passed === time || (time === 730 && passed % 365 === 0)) fresh.push(`t${time}`)
  }
  const streak = [...STREAK_MILESTONES].reverse().find((m) => c.streak >= m)
  if (streak !== undefined) {
    all.push(`s${streak}`)
    if (c.streak === streak) fresh.push(`s${streak}`)
  }
  const words = [...WORD_MILESTONES].reverse().find((m) => c.words >= m)
  if (words !== undefined) all.push(`w${words}`)
  return { all: all.length ? all : ['start'], fresh }
}

function hash(s: string): number {
  let h = 2166136261
  for (const ch of s) h = Math.imul(h ^ ch.charCodeAt(0), 16777619)
  return h >>> 0
}

const days = (n: number) => `${n} ${plural(n, 'день', 'дня', 'дней')}`

export function fillPhrase(text: string, c: PhraseContext): string {
  const passed = c.firstDay ? Math.max(0, daysBetween(c.firstDay, c.today)) : 0
  const years = Math.floor(passed / 365)
  return text
    .replaceAll('{words}', `${c.words} ${plural(c.words, 'слово', 'слова', 'слов')}`)
    .replaceAll('{streak}', days(c.streak))
    .replaceAll('{active}', days(c.activeDays))
    .replaceAll('{years}', `${years} ${plural(years, 'год', 'года', 'лет')}`)
}

/**
 * Фраза на сегодня: свежая веха (пройдена сегодня) — первой; иначе ряды (время, стрик, слова) по очереди по дням.
 * Вариант внутри группы сдвигается на 3 каждый день: в группе из 10 вчерашний не повторяется, все 10 — за 10 дней.
 */
export function pickPhrase(c: PhraseContext): Phrase {
  const day = daysBetween('2000-01-01', c.today)
  const { all, fresh } = phraseGroups(c)
  const from = fresh.length ? fresh : all
  const group = from[day % from.length]
  const list = PHRASES[group]
  const step = list.length % 3 === 0 ? 1 : 3
  const text = list[(hash(group) + day * step) % list.length]
  return { group, text: fillPhrase(text, c) }
}
